#!/usr/bin/env bash
# Regenerates src/lib/supabase/database.types.ts from supabase/migrations by
# migrating a throwaway database and introspecting it. Run after every migration:
#   npm run db:types
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/src/lib/supabase/database.types.ts"
bash "$ROOT/scripts/test-db.sh" bash -c \
  'npx supabase gen types typescript --db-url "$DATABASE_URL_TEST?sslmode=disable" --schema public 2>/dev/null' > "$OUT.tmp"
# The CLI must print only TypeScript; anything else (warnings) means a broken file.
# (Leading blank lines are fine; the CLI prints one on some machines.)
if [[ "$(grep -m1 -v '^[[:space:]]*$' "$OUT.tmp" | head -c 16)" != "export type Json" ]]; then
  echo "Unexpected output from 'supabase gen types':" >&2
  head -5 "$OUT.tmp" >&2
  rm -f -- "$OUT.tmp"
  exit 1
fi
{
  echo "// GENERATED by scripts/gen-types.sh from supabase/migrations — do not edit by hand."
  cat "$OUT.tmp"
} > "$OUT"
rm -f -- "$OUT.tmp"
npx prettier --log-level warn --write "$OUT"
echo "Wrote $OUT"
